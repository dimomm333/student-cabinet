export function presentNews<T extends { id: string; isDemo: boolean; title: string; content: string }>(item: T): T {
  const copy = item.isDemo && Object.hasOwn(copies, item.id) ? copies[item.id] : undefined;
  if (!copy) return item;
  return { ...item, title: item.title === copy.title[0] ? copy.title[1] : item.title,
    content: item.content === copy.content[0] ? copy.content[1] : item.content };
}
